# -*- coding: utf-8 -*-
"""
Файл setup.py для Lab1 - конфігурація пакета project_manager.
Використовується для встановлення пакета як модуль Python.
"""

# Імпортуємо функцію setup з setuptools для налаштування пакета
from setuptools import setup, find_packages

# Викликаємо setup з параметрами нашого пакета
setup(
    # Назва пакета - використовується при pip install
    name="project_manager",
    
    # Версія пакета - Lab1 (базова функціональність)
    version="1.0.0",
    
    # Короткий опис що робить пакет
    description="Система керування проектами - Lab1 (CRUD операції)",
    
    # Автор пакета
    author="Student",
    
    # Шлях до директорії з вихідним кодом
    package_dir={"": "src"},
    
    # Автоматично знаходимо всі пакети в директорії src
    packages=find_packages(where="src"),
    
    # Мінімальна версія Python, необхідна для роботи
    python_requires=">=3.8",
    
    # Список залежностей (інші пакети, які потрібні)
    # Для Lab1 немає зовнішніх залежностей для основного коду
    install_requires=[],
    
    # Додаткові залежності для розробки та тестування
    extras_require={
        "dev": [
            "pytest>=7.0.0",      # Фреймворк для тестування
            "pytest-cov>=4.0.0",  # Покриття коду тестами
        ],
    },
)
